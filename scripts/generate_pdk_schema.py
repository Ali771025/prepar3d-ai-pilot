"""Generate both wire mappings from the authoritative JSON schema; no SDK files are copied."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
schema = json.loads((root / 'schemas/pdk-wire-v1.json').read_text())
fields = schema['fields']
flags = schema['flags']
cpp = ['// Generated by scripts/generate_pdk_schema.py', '#pragma once', '#include <cstddef>',
       'namespace aipilot {', f'constexpr std::size_t FieldCount = {len(fields)};',
       'struct PropertySpec { const wchar_t* name; const wchar_t* unit; };',
       'constexpr PropertySpec Properties[] = {']
cpp += [f'    {{L"{f["property"]}", L"{f["unit"]}"}},' for f in fields]
cpp += ['};', 'constexpr PropertySpec Flags[] = {']
cpp += [f'    {{L"{f["property"]}", L"{f["unit"]}"}},' for f in flags]
cpp += ['};', '}']
(root / 'src/native/P3D.AIPilot.PdkBridge/WireSchema.hpp').write_text('\n'.join(cpp)+'\n')
cs = ['// Generated by scripts/generate_pdk_schema.py', 'using System;', 'using System.IO;',
      'using P3DAIPilot.Core;', 'namespace P3DAIPilot.Bridge {', 'public static class WireSchema {',
      f'public const int FieldCount = {len(fields)};',
      'public static AircraftState Read(BinaryReader r, out ulong supported) {',
      'supported = r.ReadUInt64(); uint flags = r.ReadUInt32(); uint objectId = r.ReadUInt32();',
      'var s = new AircraftState { TelemetrySource = "PDK", AircraftObjectId = objectId };']
cs += [f's.{f["name"]} = r.ReadDouble();' for f in fields]
cs += [f's.{f["name"]} = (flags & (1u << {i})) != 0;' for i,f in enumerate(flags)]
cs += ['int count = r.ReadUInt16(); if (count > 256) throw new InvalidDataException("Aircraft title too long.");',
       'byte[] title = r.ReadBytes(count); if (title.Length != count) throw new EndOfStreamException();',
       's.AircraftTitle = new System.Text.UTF8Encoding(false, true).GetString(title);',
       'if (!s.IsFinite()) throw new InvalidDataException("Non-finite telemetry."); return s; }',
       'public static void Write(BinaryWriter w, AircraftState s, ulong supported) {',
       'w.Write(supported); uint flags = 0;']
cs += [f'if (s.{f["name"]}) flags |= 1u << {i};' for i,f in enumerate(flags)]
cs += ['w.Write(flags); w.Write(s.AircraftObjectId);']
cs += [f'w.Write(s.{f["name"]});' for f in fields]
cs += ['byte[] title = System.Text.Encoding.UTF8.GetBytes(s.AircraftTitle ?? "");',
       'if (title.Length > 256) throw new InvalidDataException("Aircraft title too long.");',
       'w.Write((ushort)title.Length); w.Write(title); }', '}', '}']
(root / 'src/P3DAIPilot.Bridge/WireSchema.cs').write_text('\n'.join(cs)+'\n')
